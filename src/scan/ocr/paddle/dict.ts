// PaddleOCR の辞書ファイル（ppocrv5_dict.txt）をパースする純粋関数。
//
// 実物のファイル（public/vendor/paddleocr/ppocrv5_dict.txt）を確認したところ、
// 1行1文字で Windows 改行（CRLF）が使われている（`cat -A` で全行が `^M$` = CR LF
// になっているのを確認済み）。単純に `'\n'` だけで分割すると、各要素の末尾に
// `'\r'` が残ってしまい、辞書の文字として誤って扱われる。
//
// また、ファイルは最後の行の後にも改行があるため、素朴に split すると配列の
// 末尾に空文字列の要素が1つ余分に残る（実測: 18383行 + 末尾の空要素）。
// この空要素を辞書の1エントリとして数えてしまうと、CTC のクラスインデックスと
// 辞書の行番号が1つずれてしまう（コーディネーターの実機検証でも同じ注意点が
// 指摘されている）。そのため空行は読み飛ばす。
//
// 辞書ファイル自体に意図的な空行が含まれることは無い（1行=1グリフの前提上、
// 空文字グリフというものは存在しない）ため、空行フィルタが正当な文字を
// 取りこぼすことは無い。
export function parsePaddleDict(text: string): string[] {
  if (!text) return []
  return text.split(/\r\n|\n|\r/).filter((line) => line.length > 0)
}
