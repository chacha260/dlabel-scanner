// OCR結果に対する JS側の後処理フィルタ。エンジン側を文字種で制約する
// （文字ホワイトリストパラメータ）代わりに、既に認識済みのテキストをここで絞り込む。
// フィルタの切り替えは再認識を必要とせず、常に一瞬で反映される。
// DOM にも React にも依存しない純粋関数のみで構成する。

export type OcrFilterMode = 'raw' | 'digits' | 'alnum' | 'digitsFixed'

export const OCR_FILTER_LABELS: Record<OcrFilterMode, string> = {
  raw: 'フィルタなし（そのまま）',
  digits: '数字のみ抽出',
  alnum: '英数字のみ抽出',
  digitsFixed: '数字として解釈（誤認識を補正）',
}

/** 数字（0-9）以外をすべて取り除く */
export function filterDigitsOnly(text: string): string {
  return text.replace(/[^0-9]/g, '')
}

/** 英数字（0-9A-Za-z）と区切りに使われがちな記号（-./）以外をすべて取り除く */
export function filterAlnumOnly(text: string): string {
  return text.replace(/[^0-9A-Za-z\-./]/g, '')
}

// correctDigitConfusions の文字単位マッピング。現場からの情報どおり、現品票・Dラベルで
// 読み取りたい対象は「ほぼ数字のみ、一部に - と + が入る」だけと確定しているため、
// 通常の OCR 後処理では避けるべき（文脈を無視した）強い決定論的補正をあえてかける。
// キーは半角1文字のみを想定する（全角文字は correctDigitConfusions 側で先に
// 半角化してからこのマップに通すため、ここには半角の対応だけを書けばよい）。
//
// 各グループの根拠（見た目の形状がそのまま数字に見間違えられる、という一般的な
// 誤認識パターンに基づく。ただし現時点で実際の現品票の画像も認識ログも手元に無く、
// この対応表は実測ではなく形状からの推定である。実物で外れる組み合わせが見つかったら
// 遠慮なく削ること。特に I→1 以外は、現場からの報告があった項目ではない）:
// - I（大文字アイ）/ l（小文字エル）/ |（縦棒）/ !（感嘆符の縦棒部分）/ i（小文字アイ、
//   点を無視すれば縦棒1本）→ 1: いずれも「縦棒1本」という形状に還元できる文字で、
//   1 との判別が最も難しい。今回の不具合報告の主題そのもの。
// - O（大文字オー）/ o（小文字オー）/ D（右半分が丸い）/ Q（Oに尾がついただけ）→ 0:
//   すべて「丸い輪郭」が主要な形状要素で、数字の 0 と混同されやすい。
// - S / s → 5: 上下非対称のS字カーブが、フォントによっては 5 の上部の角が
//   丸まったものとほぼ同形になる。
// - B（大文字）→ 8: 縦に2つの丸みを持つ形状が 8 とほぼ同じ。
// - Z / z → 2: 直線的な角を持つジグザグ形状が、崩れると 2 の上部の曲線＋下部の
//   横棒に近づく。
// - G（大文字）/ b（小文字）→ 6: G は丸みに切れ込みが入った形状、b は丸に縦棒が
//   ついた形状で、どちらも 6（丸に上へ伸びる線）に近い。
// - T（大文字）→ 7: 横棒＋縦棒という単純な構成が、崩れた 7（横棒＋斜め線）と
//   判別しづらい。
// - A（大文字）→ 4: 三角形の頂点と横棒という構成が、4 の斜め線＋横棒とよく似る。
// - g / q → 9: 丸に下へ伸びる線がついた形状で、9 とほぼ同じ。
//   ※ Q（大文字）は上と同じ理由で 0 に寄せる一方、q（小文字）は下に伸びる尾の
//   向きが 9 に近いため 9 に寄せる。大文字・小文字で対応表が異なる点に注意。
// - B（大文字）→ 8 の一方で b（小文字）→ 6、Q（大文字）→ 0 の一方で q（小文字）→ 9、
//   というように、同じアルファベットでも大文字と小文字で寄せる先の数字が違う
//   ケースがある。これは意図的（見た目の違いをそのまま反映しているだけ）で、
//   バグではない。
// - —（emダッシュ）/ –（enダッシュ）/ _（アンダースコア）→ -: 現品票の版下や
//   フォントによっては区切り記号としてこれらが使われることがあるが、本アプリが
//   区切りとして扱うのは半角ハイフン - のみなので、表記ゆれとして寄せる。
const DIGIT_CONFUSION_MAP: Readonly<Record<string, string>> = {
  I: '1',
  l: '1',
  '|': '1',
  '!': '1',
  i: '1',
  O: '0',
  o: '0',
  D: '0',
  Q: '0',
  S: '5',
  s: '5',
  B: '8',
  Z: '2',
  z: '2',
  G: '6',
  b: '6',
  T: '7',
  A: '4',
  g: '9',
  q: '9',
  '—': '-',
  '–': '-',
  _: '-',
}

/**
 * 数字として読む前提で、紛らわしい文字を数字へ寄せる（決定論的な文字単位置換）。
 *
 * 通常の OCR 後処理では「文脈を見ずに文字を書き換える」のは危険（意味のある
 * 英字を潰しかねない）ため避けるべきだが、本アプリで OCR にかける対象は
 * 現場から「ほぼ数字のみ、一部記号（- +）」としか出てこないと確定しているため、
 * ここでは安全にこの強い補正をかけられる。DIGIT_CONFUSION_MAP に載っていない
 * 文字（C, E, F, H, J, K, M, N, P, R, U, V, W, X, Y や小文字の大半など）は
 * 一切変更しない＝過剰補正を避ける設計にしている。
 *
 * 処理順序:
 *   1. Unicode 正規化（NFKC）で全角英数字・全角記号を半角化する。
 *      DIGIT_CONFUSION_MAP のキーは半角1文字のみなので、全角のまま
 *      （例: 全角の "Ｉ"）だとマップに一致せず補正が効かない。必ず
 *      半角化を先に行う必要がある。NFKC は全角のハイフン（－ U+FF0D）や
 *      プラス（＋ U+FF0B）、全角数字（０-９）も半角へ正規化してくれるため、
 *      「全角英数字・全角記号の半角化」の大部分はこの1行でまかなえる。
 *   2. 半角化された文字列に対して DIGIT_CONFUSION_MAP による1文字ずつの
 *      置換を行う。
 */
export function correctDigitConfusions(text: string): string {
  const halfWidth = text.normalize('NFKC')
  let result = ''
  for (const ch of halfWidth) {
    result += DIGIT_CONFUSION_MAP[ch] ?? ch
  }
  return result
}

/**
 * correctDigitConfusions で紛らわしい文字を数字へ寄せたうえで、数字と
 * 区切り記号（- +）以外を取り除く。
 *
 * 必ず「補正してから除去する」順序で行うこと。先に除去してしまうと、
 * まだ数字に化ける前の I や O や S がその時点では「数字でも - + でもない
 * 文字」として消えてしまい、1 や 0 や 5 に補正される機会を失ってしまう。
 */
function filterDigitsFixed(text: string): string {
  return correctDigitConfusions(text).replace(/[^0-9\-+]/g, '')
}

/** 指定したモードでテキストをフィルタする（'raw' はそのまま返す） */
export function applyOcrFilter(text: string, mode: OcrFilterMode): string {
  if (mode === 'digits') return filterDigitsOnly(text)
  if (mode === 'alnum') return filterAlnumOnly(text)
  if (mode === 'digitsFixed') return filterDigitsFixed(text)
  return text
}
